use crate::ImportResult;

pub fn import_pdf(bytes: &[u8]) -> Result<ImportResult, Box<dyn std::error::Error + Send + Sync>> {
    // Extract full text across all pages with full Adobe CMap & ToUnicode support
    let full_text = match pdf_extract::extract_text_from_mem(bytes) {
        Ok(t) => t,
        Err(_) => {
            // Fallback to lopdf page-by-page if pdf-extract fails
            let doc = lopdf::Document::load_mem(bytes)?;
            let pages = doc.get_pages();
            let mut combined = String::new();
            for (&page_num, _) in &pages {
                if let Ok(t) = doc.extract_text(&[page_num]) {
                    combined.push_str(&t);
                    combined.push('\x0C'); // Form feed page delimiter
                }
            }
            combined
        }
    };

    // Split pages by Form Feed (\x0C) or double newlines
    let raw_pages: Vec<&str> = if full_text.contains('\x0C') {
        full_text.split('\x0C').collect()
    } else {
        vec![&full_text]
    };

    let mut section_xmls: Vec<String> = Vec::new();

    for page_str in raw_pages {
        let lines: Vec<&str> = page_str
            .lines()
            .map(|l| l.trim())
            .filter(|l| !l.is_empty())
            .collect();

        if lines.is_empty() {
            continue;
        }

        let mut page_nodes: Vec<String> = Vec::new();

        for line in lines {
            let escaped = escape_xml(line);

            // Heuristics for headings:
            // 1. Short and all-caps or title case with no period
            // 2. Headings like "Existing System:", "Proposed System:", "Hardware Requirements:"
            if (line.len() < 50 && line.chars().all(|c| !c.is_alphabetic() || c.is_uppercase()))
                || line.starts_with("# ")
                || line.ends_with(':') && line.len() < 40
            {
                page_nodes.push(format!("      <h2>{}</h2>", escaped.trim_start_matches("# ")));
            } else if line.len() < 60 && !line.ends_with('.') && !line.ends_with(';') && !line.contains(" e.g.,") {
                page_nodes.push(format!("      <h3>{}</h3>", escaped));
            } else {
                page_nodes.push(format!("      <p>{}</p>", escaped));
            }
        }

        if !page_nodes.is_empty() {
            section_xmls.push(format!(
                "    <section page-style=\"body\">\n{}\n    </section>",
                page_nodes.join("\n")
            ));
        }
    }

    if section_xmls.is_empty() {
        section_xmls.push("    <section page-style=\"body\">\n      <p>Empty document</p>\n    </section>".to_string());
    }

    let dxml = format!(
        r#"<doc>
  <props>
    <meta>
      <title>Imported PDF Document</title>
      <author>Pagina Reverse-Engineering Engine</author>
    </meta>
    <paper size="A4" orientation="portrait" margin="20mm" />
    <link rel="stylesheet" href="styles.dcss" />
    <page-styles>
      <page-style name="body" default="true">
        <running-header>
          <left><text>Imported PDF</text></left>
          <right><page-number/> of <total-pages/></right>
        </running-header>
        <running-footer>
          <center><text>Pagina Engine</text></center>
        </running-footer>
      </page-style>
    </page-styles>
  </props>

  <body>
{}
  </body>
</doc>"#,
        section_xmls.join("\n\n")
    );

    let dcss = r#"/* Generated by Pagina PDF Reverse-Engineering Engine */
h1 {
  font-size: 24pt;
  font-weight: bold;
  color: #1e3a8a;
  margin-bottom: 5mm;
}

h2 {
  font-size: 16pt;
  font-weight: bold;
  color: #0f172a;
  margin-top: 6mm;
  margin-bottom: 3mm;
}

h3 {
  font-size: 13pt;
  font-weight: 600;
  color: #1e293b;
  margin-top: 4mm;
  margin-bottom: 2mm;
}

p {
  font-size: 10.5pt;
  line-height: 1.6;
  color: #334155;
  margin-bottom: 3mm;
}
"#.to_string();

    Ok(ImportResult { dxml, dcss })
}

fn escape_xml(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
        .replace('\'', "&apos;")
}
