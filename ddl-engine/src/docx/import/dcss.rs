use std::collections::HashMap;

use super::types::{ImportedTextStyle, ParsedGenericPart};

pub fn generate_imported_dcss(
    document_styles: &HashMap<String, ImportedTextStyle>,
    font_counts: &HashMap<String, usize>,
    font_size_counts: &HashMap<u32, usize>,
    font_color_counts: &HashMap<String, usize>,
    parsed_header: &ParsedGenericPart,
    parsed_footer: &ParsedGenericPart,
) -> String {
    let normal_style = document_styles
        .get("Normal")
        .or_else(|| document_styles.get("normal"));
    let body_half_pts = normal_style
        .and_then(|style| style.font_size_half_points)
        .or_else(|| {
            font_size_counts
                .iter()
                .max_by_key(|&(_, count)| count)
                .map(|(&sz, _)| sz)
        })
        .unwrap_or(28);

    let body_pt = (body_half_pts as f32) / 2.0;

    let mut sorted_larger_sizes: Vec<u32> = font_size_counts
        .keys()
        .copied()
        .filter(|&sz| sz > body_half_pts)
        .collect();
    sorted_larger_sizes.sort_unstable();

    let style_size = |name: &str| {
        document_styles
            .get(name)
            .and_then(|style| style.font_size_half_points)
            .map(|size| size as f32 / 2.0)
    };
    let h1_pt = style_size("Heading1")
        .or_else(|| sorted_larger_sizes.pop().map(|sz| (sz as f32) / 2.0))
        .unwrap_or(body_pt + 4.0);
    let h2_pt = style_size("Heading2")
        .or_else(|| sorted_larger_sizes.pop().map(|sz| (sz as f32) / 2.0))
        .unwrap_or((body_pt + 2.0).min(h1_pt));
    let h3_pt = style_size("Heading3").unwrap_or(body_pt);

    let primary_font = normal_style
        .and_then(|style| style.font_family.clone())
        .or_else(|| {
            font_counts
                .iter()
                .max_by_key(|&(_, count)| count)
                .map(|(name, _)| name.clone())
        })
        .unwrap_or_else(|| "Times New Roman".to_string());

    let font_family_stack = {
        let lower = primary_font.to_lowercase();
        if lower.contains("times")
            || lower.contains("serif")
            || lower.contains("georgia")
            || lower.contains("garamond")
            || lower.contains("cambria")
        {
            format!("\"{}\", Times, serif", primary_font)
        } else if lower.contains("consolas") || lower.contains("courier") || lower.contains("mono") {
            format!("\"{}\", Consolas, monospace", primary_font)
        } else {
            format!(
                "\"{}\", -apple-system, BlinkMacSystemFont, \"Segoe UI\", Roboto, sans-serif",
                primary_font
            )
        }
    };

    let primary_color = normal_style
        .and_then(|style| style.color.as_ref().map(|color| format!("#{}", color)))
        .or_else(|| {
            font_color_counts
                .iter()
                .max_by_key(|&(_, count)| count)
                .map(|(c, _)| c.clone())
        })
        .unwrap_or_else(|| "#000000".to_string());

    let style_color = |name: &str| {
        document_styles
            .get(name)
            .and_then(|style| style.color.as_ref().map(|color| format!("#{}", color)))
    };
    let h1_color = style_color("Heading1").unwrap_or_else(|| primary_color.clone());
    let h2_color = style_color("Heading2").unwrap_or_else(|| primary_color.clone());
    let h3_color = style_color("Heading3").unwrap_or_else(|| primary_color.clone());

    let header_max_h = parsed_header
        .max_image_height_mm
        .map(|h| (h + 1.0).round().max(25.0) as u32)
        .unwrap_or(35);

    let footer_max_h = parsed_footer
        .max_image_height_mm
        .map(|h| (h + 1.0).round().max(25.0) as u32)
        .unwrap_or(35);

    let lead_pt = body_pt + 1.0;

    format!(
        r#"/* Generated by Pagina OpenXML Reverse Engine */
body {{
  font-family: {font_family_stack};
  font-size: {body_pt}pt;
  color: {primary_color};
  line-height: 1.35;
}}

h1 {{
  font-family: {font_family_stack};
  font-size: {h1_pt}pt;
  font-weight: bold;
  color: {h1_color};
  margin-top: 4mm;
  margin-bottom: 2.5mm;
}}

h2 {{
  font-family: {font_family_stack};
  font-size: {h2_pt}pt;
  font-weight: bold;
  color: {h2_color};
  margin-top: 3.5mm;
  margin-bottom: 2mm;
}}

h3 {{
  font-family: {font_family_stack};
  font-size: {h3_pt}pt;
  font-weight: bold;
  color: {h3_color};
  margin-top: 3mm;
  margin-bottom: 1.5mm;
}}

p {{
  font-family: {font_family_stack};
  font-size: {body_pt}pt;
  line-height: 1.35;
  color: {primary_color};
  margin-bottom: 2.5mm;
}}

p.lead {{
  font-size: {lead_pt}pt;
  color: {primary_color};
}}

blockquote {{
  margin-left: 6mm;
  padding-left: 4mm;
  border-left: 3px solid #cbd5e1;
  color: {primary_color};
  margin-bottom: 4mm;
}}

ul, ol {{
  padding-left: 24px;
  margin-top: 2mm;
  margin-bottom: 2.5mm;
}}

li {{
  font-family: {font_family_stack};
  font-size: {body_pt}pt;
  margin-bottom: 1.5mm;
  line-height: 1.35;
}}

.callout {{
  background-color: #f0fdf4;
  border-left: 4px solid #16a34a;
  padding: 4mm 6mm;
  margin: 4mm 0;
  border-radius: 4px;
}}

.col-box {{
  background-color: #f8fafc;
  border: 1px solid #e2e8f0;
  border-radius: 6px;
  padding: 4mm;
}}

code {{
  font-family: Consolas, monospace;
  background-color: #f1f5f9;
  padding: 1px 4px;
  border-radius: 3px;
  font-size: 9.5pt;
}}

table {{
  font-family: {font_family_stack};
  font-size: {body_pt}pt;
  width: 100%;
  border-collapse: collapse;
  margin: 3mm 0;
}}

table.borderless {{
  border: none !important;
}}

table.align-right {{
  margin-left: auto !important;
  margin-right: 0 !important;
  width: 48% !important;
}}

th, td {{
  font-family: {font_family_stack};
  font-size: {body_pt}pt;
  padding: 1.5mm 3mm;
  line-height: 1.3;
}}

th {{
  border: 1px solid #cbd5e1;
  background-color: #f8fafc;
  font-weight: bold;
}}

td {{
  border: 1px solid #cbd5e1;
}}

table.borderless td,
table.borderless th {{
  border: none !important;
  background: transparent !important;
}}

p[align="center"], h1[align="center"], h2[align="center"] {{
  text-align: center;
}}

p[align="right"] {{
  text-align: right;
}}

p[align="justify"] {{
  text-align: justify;
}}

/* Header & Footer Layout & Positioning */
header, running-header, .running-header {{
  width: 100%;
  display: flex;
  justify-content: space-between;
  align-items: center;
  margin-bottom: 3mm;
}}

.running-header .header-left, header .header-left {{
  text-align: left;
}}

.running-header .header-center, header .header-center {{
  text-align: center;
}}

.running-header .header-right, header .header-right {{
  text-align: right;
}}

.header-image, running-header img, header img {{
  max-height: {header_max_h}mm;
  width: auto;
  max-width: 100%;
  display: block;
  margin: 0 auto;
}}

footer, running-footer, .running-footer {{
  width: 100%;
  margin-top: auto;
  display: flex;
  justify-content: space-between;
  align-items: center;
}}

.running-footer .footer-left, footer .footer-left {{
  text-align: left;
}}

.running-footer .footer-center, footer .footer-center {{
  text-align: center;
}}

.running-footer .footer-right, footer .footer-right {{
  text-align: right;
}}

.footer-image, running-footer img, footer img {{
  max-height: {footer_max_h}mm;
  width: auto;
  max-width: 100%;
  display: block;
  margin: 0 auto;
}}
"#
    )
}
